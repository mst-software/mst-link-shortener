<?php

namespace App\Support;

use App\Exceptions\MediaUploadException;
use App\Services\Settings;
use Illuminate\Support\Facades\Storage;
use Throwable;

/**
 * Stores uploaded media on the disk chosen on the admin Storage settings page and turns the stored
 * references back into URLs.
 *
 * A reference is the path on the disk, prefixed with "s3:" for files on the S3 disk. Plain paths are on
 * the public disk, which keeps paths saved before the S3 option existed working, and lets each file keep
 * working from where it was saved after the operator switches disks.
 */
class MediaStorage
{
    public const DISK_PUBLIC = 'public';

    public const DISK_S3 = 's3';

    /**
     * Disks an operator can choose from.
     *
     * @var array<string, string>
     */
    public const DISKS = [
        self::DISK_PUBLIC => 'This server (public folder)',
        self::DISK_S3 => 'S3-compatible storage (Amazon S3, Cloudflare R2, MinIO and others)',
    ];

    /**
     * Stored paths are generated by MediaUploader: folders and file names of letters, digits, "-" and "_".
     */
    private const PATH_PATTERN = '#^[A-Za-z0-9_-]+(/[A-Za-z0-9_-]+)*\.[A-Za-z0-9]{1,5}\z#';

    /**
     * The disk new uploads go to.
     */
    public static function currentDisk(): string
    {
        $disk = Settings::string('upload_disk', self::DISK_PUBLIC);

        return array_key_exists($disk, self::DISKS) ? $disk : self::DISK_PUBLIC;
    }

    /**
     * Write the contents to the current disk and return the reference to save.
     *
     * @throws MediaUploadException
     */
    public static function put(string $path, string $contents): string
    {
        $disk = self::currentDisk();

        try {
            $written = Storage::disk($disk)->put($path, $contents);
        } catch (Throwable $exception) {
            report($exception);
            $written = false;
        }

        if (! $written) {
            throw new MediaUploadException('The image could not be saved. Check the storage settings and use "Test connection".');
        }

        return $disk === self::DISK_PUBLIC ? $path : $disk.':'.$path;
    }

    /**
     * Public URL of a stored reference, or null when there is none.
     */
    public static function url(?string $reference): ?string
    {
        $location = self::parse($reference);

        return $location === null ? null : Storage::disk($location['disk'])->url($location['path']);
    }

    /**
     * Delete the file of a stored reference. Failures are reported, never thrown, so replacing an
     * image never fails because the old file is already gone.
     */
    public static function delete(?string $reference): void
    {
        $location = self::parse($reference);

        if ($location === null) {
            return;
        }

        try {
            Storage::disk($location['disk'])->delete($location['path']);
        } catch (Throwable $exception) {
            report($exception);
        }
    }

    /**
     * Split a reference into its disk and path. Anything that is not a path MediaUploader could have
     * written (absolute paths, "..", URLs) is ignored, so a stored value can never reach other files.
     *
     * @return array{disk: string, path: string}|null
     */
    public static function parse(?string $reference): ?array
    {
        if ($reference === null || $reference === '') {
            return null;
        }

        $disk = self::DISK_PUBLIC;
        $path = $reference;

        if (str_starts_with($reference, self::DISK_S3.':')) {
            $disk = self::DISK_S3;
            $path = substr($reference, strlen(self::DISK_S3) + 1);
        }

        if (preg_match(self::PATH_PATTERN, $path) !== 1) {
            return null;
        }

        return ['disk' => $disk, 'path' => $path];
    }
}
